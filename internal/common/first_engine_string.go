package common

// FirstEngineString returns the first string of a possibly list-shaped engine
// field. Lists yield element zero only — no trimming and no search for a later
// string — matching the strict contract used by artifact and wiki services.
func FirstEngineString(v any) string {
	switch t := v.(type) {
	case string:
		return t
	case []string:
		if len(t) > 0 {
			return t[0]
		}
	case []any:
		if len(t) > 0 {
			if s, ok := t[0].(string); ok {
				return s
			}
		}
	}
	return ""
}
